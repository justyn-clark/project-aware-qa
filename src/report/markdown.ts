// Risk report (Phase 4)
// ---------------------------------------------------------------------------

export function renderRiskReport(registry: SurfaceRegistry): string {
	const lines: string[] = [];
	lines.push(header("QA Risk Report", registry.generatedAt, registry.project.root));
	const { high, medium, low } = registry.stats.byRisk;
	lines.push(
		`\n**${high} high · ${medium} medium · ${low} low** across ${registry.surfaces.length} surfaces.\n`,
	);

	for (const level of ["high", "medium", "low"] as Risk[]) {
		const group = registry.surfaces.filter((s) => s.risk === level);
		if (!group.length) continue;
		lines.push(`\n## ${RISK_BADGE[level]} (${group.length})\n`);
		lines.push(
			table(
				["Score", "Type", "Surface", "Entity", "Top reason"],
				group
					.slice(0, level === "high" ? 200 : 60)
					.map((s) => [
						String(s.riskScore),
						s.type,
						s.title.slice(0, 60),
						s.entity ?? "—",
						(s.riskReasons[0] ?? "—").replace(/\s*\(\+\d+\)$/, ""),
					]),
			),
		);
		if (group.length > (level === "high" ? 200 : 60)) {
			lines.push(
				`\n_…and ${group.length - (level === "high" ? 200 : 60)} more (see surface-registry.json)._`,
			);
		}
	}
	lines.push("");
	return lines.join("\n");
}

// ---------------------------------------------------------------------------
// QA test plan (Phase 5)
// ---------------------------------------------------------------------------

const DEPTH_BY_RISK: Record<Risk, string> = {
	high: "runtime + form + API + cache + screenshots",
	medium: "route/API + basic UI",
	low: "smoke only",
};

function planStepsForSurface(s: Surface): string[] {
	const steps: string[] = [];
	for (const t of s.inferredTests) {
		const mark = t.status === "present" ? "↺ (has test)" : "☐ (no test)";
		steps.push(`- ${mark} **${t.kind}**: ${t.description}`);
	}
	if (s.gaps.length) {
		for (const g of s.gaps.slice(0, 4)) steps.push(`  - ⚠ ${g}`);
	}
	return steps;
}

export interface PlanOptions {
	/** Optional scope filter: entity name, surface type, risk level, or "admin". */
	scope?: string;
	/** Cap surfaces listed per risk tier. */
	limitPerTier?: number;
}

function matchesScope(s: Surface, scope: string): boolean {
	const q = scope.toLowerCase().trim();
	if (!q) return true;
	if (q === "admin") return /admin/i.test(s.title) || s.riskReasons.some((r) => /admin/.test(r));
	if (["high", "medium", "low"].includes(q)) return s.risk === q;
	if (
		(
			[
				"crud-flow",
				"form",
				"api-endpoint",
				"route",
				"cache-risk",
				"visual-page",
				"test-gap",
			] as SurfaceType[]
		).includes(q as SurfaceType)
	) {
		return s.type === q;
	}
	return (s.entity ?? "").toLowerCase().includes(q) || s.title.toLowerCase().includes(q);
}

export function renderTestPlan(registry: SurfaceRegistry, options: PlanOptions = {}): string {
	const lines: string[] = [];
	lines.push(header("QA Test Plan", registry.generatedAt, registry.project.root));
	const scope = options.scope?.trim();
	if (scope) lines.push(`\n_Scope: \`${scope}\`_\n`);
	lines.push(
		"\nThis plan states what to test for each surface **regardless of whether a test currently exists**.\n" +
			"Depth scales with risk: high → full runtime; medium → route/API + basic UI; low → smoke.\n",
	);

	const selected = registry.surfaces.filter((s) => (scope ? matchesScope(s, scope) : true));
	const limit = options.limitPerTier ?? 40;

	if (!selected.length) {
		lines.push(`\n_No surfaces matched scope \`${scope}\`._\n`);
		return lines.join("\n");
	}

	lines.push("\n## Coverage summary\n");
	const present = selected
		.flatMap((s) => s.inferredTests)
		.filter((t) => t.status === "present").length;
	const missing = selected
		.flatMap((s) => s.inferredTests)
		.filter((t) => t.status === "missing").length;
	lines.push(`- Surfaces in scope: **${selected.length}**`);
	lines.push(`- Inferred tests: **${present} present**, **${missing} missing**`);

	for (const level of ["high", "medium", "low"] as Risk[]) {
		const group = selected.filter((s) => s.risk === level);
		if (!group.length) continue;
		lines.push(`\n## ${RISK_BADGE[level]} — depth: ${DEPTH_BY_RISK[level]} (${group.length})\n`);
		for (const s of group.slice(0, limit)) {
			lines.push(`\n### ${s.title}`);
			const meta = [
				`type: \`${s.type}\``,
				s.entity ? `entity: \`${s.entity}\`` : "",
				s.frontendRoute ? `route: \`${s.frontendRoute}\`` : "",
				s.backendEndpoint ? `endpoint: \`${s.backendEndpoint}\`` : "",
				`score: ${s.riskScore}`,
			].filter(Boolean);
			lines.push(`_${meta.join(" · ")}_`);
			lines.push(
				`files: ${s.files
					.slice(0, 5)
					.map((f) => `\`${f}\``)
					.join(", ")}`,
			);
			lines.push(...planStepsForSurface(s));
		}
		if (group.length > limit)
			lines.push(`\n_…and ${group.length - limit} more ${level} surfaces (filter with a scope)._`);
	}
	lines.push("");
	return lines.join("\n");
}
