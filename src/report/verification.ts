/**
 * Verification report rendering (Phase 6) + repair-loop finding scaffold (Phase 9).
 *
 * The cardinal rule: no claim without evidence. Every check row links to its command log
 * or states why it was skipped. Failed checks are expanded into repair-loop findings with
 * the required fields (issue / evidence / suspected cause / fix status / rerun evidence /
 * remaining gap) so the agent can drive scan → plan → verify → fix → verify → report.
 */

import type { CheckResult, VerifyResult } from "../verify/index.js";
import { classifyProbe, type RouteProbe } from "../verify/playwright.js";

function probeResultLabel(p: RouteProbe): string {
	const note = p.note ? ` (${p.note})` : "";
	switch (classifyProbe(p)) {
		case "ok":
			return `✅ ok${note}`;
		case "auth":
			return `🔒 auth-gated (${p.status})`;
		case "broken":
			return `❌ broken (${p.status})`;
		default:
			return `❌ unreachable${p.error ? `: ${p.error}` : ""}`.slice(0, 60);
	}
}

const STATUS_BADGE: Record<CheckResult["status"], string> = {
	passed: "✅ passed",
	failed: "❌ failed",
	skipped: "⚪ skipped",
	inconclusive: "🟡 inconclusive",
};

function esc(s: string): string {
	return s.replace(/\|/g, "\\|");
}

function table(headers: string[], rows: string[][]): string {
	const head = `| ${headers.join(" | ")} |`;
	const sep = `| ${headers.map(() => "---").join(" | ")} |`;
	const body = rows.map((r) => `| ${r.map((c) => esc(c)).join(" | ")} |`).join("\n");
	return rows.length ? `${head}\n${sep}\n${body}` : `${head}\n${sep}`;
}

function repairLoopBlock(check: CheckResult): string[] {
	const lines: string[] = [];
	lines.push(`\n### ❌ ${check.title}\n`);
	lines.push(`- **Issue**: ${check.summary ?? check.reason ?? "check failed"}`);
	lines.push(
		`- **Evidence**: ${check.evidencePath ? `\`.qa/${check.evidencePath}\`` : "—"}${
			check.command ? ` · command: \`${check.command}\`` : ""
		}${typeof check.exitCode === "number" ? ` · exit ${check.exitCode}` : ""}`,
	);
	lines.push("- **Suspected cause**: _fill in after inspecting the evidence above_");
	lines.push("- **Fix status**: ☐ not started");
	lines.push("- **Rerun evidence**: _re-run `/qa-verify` after fixing and link the new log_");
	lines.push("- **Remaining gap**: _note anything still unverified_");
	return lines;
}

export function renderVerificationReport(result: VerifyResult): string {
	const lines: string[] = [];
	lines.push(`# QA Verification Report\n`);
	lines.push(`_Generated by project-aware-qa at ${result.generatedAt}_`);
	lines.push(
		`_Target: \`${result.root}\` · package manager: \`${result.project.packageManager}\`_\n`,
	);
	if (result.selection) {
		lines.push("## Change selection\n");
		lines.push(
			`Base \`${result.selection.baseRef}\` (\`${result.selection.baseCommit.slice(0, 12)}\`) · ${result.selection.changedFiles.length} changed files · ${result.selection.stackRoots.length} stacks · ${result.selection.surfaceIds.length} directly affected surfaces.\n`,
		);
		if (result.selection.globalImpact) {
			lines.push(
				"A root/shared change conservatively selected every detected stack and surface.\n",
			);
		}
	}

	const passed = result.checks.filter((c) => c.status === "passed").length;
	const failed = result.checks.filter((c) => c.status === "failed").length;
	const skipped = result.checks.filter((c) => c.status === "skipped").length;
	const inconclusive = result.checks.filter((c) => c.status === "inconclusive").length;
	const incBit = inconclusive ? ` · ${inconclusive} inconclusive` : "";
	lines.push(`**${passed} passed · ${failed} failed · ${skipped} skipped${incBit}**\n`);
	if (result.policy) {
		lines.push("## Policy\n");
		lines.push(
			`${result.policy.passed ? "✅ passed" : "❌ failed"} · required: ${result.policy.requiredChecks.length ? result.policy.requiredChecks.map((check) => `\`${check}\``).join(", ") : "none"} · fail on incomplete: ${result.policy.failOnIncomplete ? "yes" : "no"}\n`,
		);
		for (const violation of result.policy.violations) lines.push(`- ${violation}`);
		lines.push("");
	}

	lines.push("## Checks\n");
	lines.push(
		table(
			["Check", "Status", "Detail", "Evidence"],
			result.checks.map((c) => [
				c.title,
				STATUS_BADGE[c.status],
				c.status === "skipped" || c.status === "inconclusive"
					? (c.reason ?? c.summary ?? "—")
					: (c.summary ?? "—"),
				c.evidencePath ? `\`.qa/${c.evidencePath}\`` : c.command ? `\`${c.command}\`` : "—",
			]),
		),
	);

	// Targeted route checks detail.
	if (result.probes.length) {
		lines.push("\n## Targeted route checks\n");
		lines.push(`Base URL: \`${result.baseUrl}\`\n`);
		lines.push(
			table(
				["Route", "Status", "ms", "Result"],
				result.probes.map((p) => [
					p.route,
					p.status === null ? "—" : String(p.status),
					String(p.durationMs),
					probeResultLabel(p),
				]),
			),
		);
	}

	// Screenshots detail (rendered-DOM check).
	if (result.screenshots.length) {
		lines.push("\n## Screenshots (rendered-DOM check)\n");
		lines.push(
			table(
				["Route", "Viewport", "HTTP", "DOM", "Console", "File"],
				result.screenshots.map((s) => [
					s.route,
					s.viewport,
					s.httpStatus == null ? "—" : String(s.httpStatus),
					s.looksLikeNotFound
						? "❌ not-found/error"
						: s.file
							? "✅ rendered"
							: `❌ ${s.error ?? "failed"}`.slice(0, 40),
					s.consoleErrors ? `⚠ ${s.consoleErrors}` : "0",
					s.file ? `\`.qa/${(s.file ?? "").split("/.qa/").pop() ?? s.file}\`` : "—",
				]),
			),
		);
	}

	// Repair-loop findings for every failed check.
	const failures = result.checks.filter((c) => c.status === "failed");
	lines.push("\n## Findings (repair loop)\n");
	if (failures.length === 0) {
		lines.push(
			"_No failing checks. Skipped checks are gated brakes or missing prerequisites — see the table above._",
		);
	} else {
		lines.push(
			"Each failing check below follows the repair-loop format. Do not mark a finding resolved without rerun evidence.\n",
		);
		for (const c of failures) lines.push(...repairLoopBlock(c));
	}

	lines.push("\n## Honesty ledger\n");
	lines.push(
		"- Claims are backed by the linked command logs under the verification run directory.",
	);
	if (skipped > 0)
		lines.push(
			`- ${skipped} check(s) were **skipped** — each lists its reason and is **not** counted as passing.`,
		);
	if (inconclusive > 0) {
		lines.push(
			`- ${inconclusive} check(s) were **inconclusive** — the signal couldn't validate the claim (e.g. a SPA returns 200 for unknown paths). Not a pass and not a fail; see the reason and the rendered-DOM/screenshot check.`,
		);
	}
	lines.push(
		"- Screenshots, full test runs and dependency installs are gated; enable them explicitly to execute.",
	);
	lines.push("");
	return lines.join("\n");
}
