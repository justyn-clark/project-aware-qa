/**
 * Markdown report rendering for every `.qa/*.md` artifact except the verification
 * report (which is owned by the verifier). Pure string functions over the scan result
 * and registry, so they are trivially testable and deterministic.
 */
import type { CrudFlow, CrudOp } from "../inference/crud.js";
import type { ScanResult } from "../scanner/index.js";
import type { Risk, Surface, SurfaceRegistry, SurfaceType } from "../types.js";

const RISK_BADGE: Record<Risk, string> = { high: "🔴 high", medium: "🟠 medium", low: "🟢 low" };
const CRUD_OPS: CrudOp[] = ["create", "read", "list", "update", "delete"];

function esc(s: string): string {
	return s.replace(/\|/g, "\\|");
}

function table(headers: string[], rows: string[][]): string {
	const head = `| ${headers.join(" | ")} |`;
	const sep = `| ${headers.map(() => "---").join(" | ")} |`;
	const body = rows.map((r) => `| ${r.map((c) => esc(c)).join(" | ")} |`).join("\n");
	return rows.length
		? `${head}\n${sep}\n${body}`
		: `${head}\n${sep}\n| ${headers.map(() => "—").join(" | ")} |`;
}

function countBy<T>(items: T[], key: (t: T) => string): Record<string, number> {
	const out: Record<string, number> = {};
	for (const i of items) out[key(i)] = (out[key(i)] ?? 0) + 1;
	return out;
}

function header(title: string, generatedAt: string, root: string): string {
	return `# ${title}\n\n_Generated by project-aware-qa at ${generatedAt}_\n_Target: \`${root}\`_\n`;
}

// ---------------------------------------------------------------------------
// Scan report (Phase 2)
// ---------------------------------------------------------------------------

export function renderScanReport(result: ScanResult): string {
	const { project, bundle, playwright, registry } = result;
	const lines: string[] = [];
	lines.push(header("QA Scan Report", registry.generatedAt, project.root));

	lines.push("\n## Project\n");
	lines.push(
		table(
			["Property", "Value"],
			[
				["Name", project.name ?? "—"],
				[
					"Stacks",
					project.stacks.map((s) => `${s.label}${s.rootRel ? ` @${s.rootRel}` : ""}`).join(", ") ||
						"—",
				],
				["Frameworks", project.frameworks.join(", ") || "—"],
				["Test runners", project.testRunners.join(", ") || "—"],
				["Build files", String(project.packageJsonPaths.length)],
				[
					"Files scanned",
					String(registry.stats.scannedFiles) + (result.repo.truncated ? " (truncated)" : ""),
				],
			],
		),
	);

	lines.push("\n### Runnable checks (per stack)\n");
	if (project.stacks.length === 0) {
		lines.push("_No recognized stack detected._");
	}
	for (const s of project.stacks) {
		const c = s.checks;
		lines.push(`\n**${s.label}${s.rootRel ? ` @${s.rootRel}` : ""}** (${s.depth})`);
		lines.push(
			table(
				["Check", "Command"],
				(["typecheck", "lint", "test", "build", "dev"] as const).map((k) => [
					k,
					c[k] ? `\`${c[k]?.command}\`` : "— (none found)",
				]),
			),
		);
	}

	lines.push("\n## Detected surfaces\n");
	lines.push(
		table(
			["Layer", "Count"],
			[
				["Frontend routes", String(bundle.routes.length)],
				["Backend endpoints", String(bundle.endpoints.length)],
				["DTOs", String(bundle.dtos.length)],
				["Forms", String(bundle.forms.length)],
				["Cache/invalidation signals", String(bundle.cacheSignals.length)],
				["Test files", String(bundle.tests.length)],
				["Playwright config", playwright.present ? `yes (${playwright.configFile})` : "no"],
			],
		),
	);

	lines.push("\n### Surfaces by type\n");
	lines.push(
		table(
			["Type", "Count"],
			Object.entries(registry.stats.byType).map(([t, c]) => [t, String(c)]),
		),
	);

	lines.push("\n### Surfaces by risk\n");
	lines.push(
		table(
			["Risk", "Count"],
			(["high", "medium", "low"] as Risk[]).map((r) => [
				RISK_BADGE[r],
				String(registry.stats.byRisk[r]),
			]),
		),
	);

	const cacheByLib = countBy(bundle.cacheSignals, (s) => s.library);
	if (Object.keys(cacheByLib).length) {
		lines.push("\n### Cache/data libraries in use\n");
		lines.push(
			table(
				["Library", "Signals"],
				Object.entries(cacheByLib).map(([l, c]) => [l, String(c)]),
			),
		);
	}

	lines.push("\n## Next steps\n");
	lines.push("- Review `crud-matrix.md` and `risk-report.md` for admin/CRUD coverage.");
	lines.push("- Run `/qa-plan` to generate a risk-ranked test plan.");
	lines.push("- Run `/qa-verify` to execute available checks and capture screenshots.");
	lines.push("");
	return lines.join("\n");
}

// ---------------------------------------------------------------------------
// CRUD matrix (Phase 4)
// ---------------------------------------------------------------------------

export function renderCrudMatrix(flows: CrudFlow[], registry: SurfaceRegistry): string {
	const lines: string[] = [];
	lines.push(header("CRUD / Admin Matrix", registry.generatedAt, registry.project.root));
	lines.push(
		"\nEntities inferred from routes, controllers, forms and DTOs. ✓ = handler/route detected for that operation.\n",
	);

	const rows = flows.map((f) => {
		const ops = CRUD_OPS.map((op) => (f.operations[op] ? "✓" : "·"));
		const tests = registry.surfaces.find((s) => s.type === "crud-flow" && s.entity === f.entity);
		return [
			f.entity + (f.isAdmin ? " 🛠" : ""),
			...ops,
			String(f.forms.length),
			String(f.dtos.length),
			tests ? RISK_BADGE[tests.risk] : "—",
		];
	});
	lines.push(table(["Entity", "C", "R", "L", "U", "D", "Forms", "DTOs", "Risk"], rows));

	lines.push("\n## Flow detail\n");
	for (const f of flows) {
		lines.push(`\n### ${f.entity}${f.isAdmin ? " (admin)" : ""}\n`);
		if (f.routes.length) {
			lines.push("**Routes**");
			for (const r of f.routes.slice(0, 12)) {
				lines.push(
					`- \`${r.routePath}\`${r.hasLoader ? " ·loader" : ""}${r.hasAction ? " ·action" : ""} — \`${r.file}\``,
				);
			}
		}
		if (f.endpoints.length) {
			lines.push("\n**Endpoints**");
			for (const e of f.endpoints.slice(0, 16)) {
				lines.push(
					`- \`${e.method} ${e.path}\` → \`${e.controller}.${e.handler}\`${e.bodyDto ? ` (body: ${e.bodyDto})` : ""}`,
				);
			}
		}
		for (const l of f.formEndpointLinks) {
			lines.push(
				`\n**Form** \`${l.form.file}\` → ${l.endpoint ? `\`${l.endpoint.method} ${l.endpoint.path}\`` : "_no matched endpoint_"}`,
			);
			lines.push(`- fields: ${l.form.fields.join(", ") || "—"}`);
			if (l.missingDtoFields.length)
				lines.push(`- ⚠ missing required DTO fields: ${l.missingDtoFields.join(", ")}`);
			if (l.unmatchedFormFields.length)
				lines.push(`- ⚠ form fields absent from DTO: ${l.unmatchedFormFields.join(", ")}`);
		}
		const stale = f.mutationLinks.filter((m) => m.staleRisk);
		if (stale.length) {
			lines.push("\n**⚠ Mutations without detected cache invalidation**");
			for (const m of stale) lines.push(`- ${m.mutation} — \`${m.file}:${m.line}\``);
		}
	}
	lines.push("");
	return lines.join("\n");
}

